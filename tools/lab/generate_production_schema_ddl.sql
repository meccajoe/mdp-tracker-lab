-- Standalone and serial sequences; identity sequences are created by tables.
SELECT format('CREATE SEQUENCE public.%I AS %s INCREMENT BY %s MINVALUE %s MAXVALUE %s START WITH %s CACHE %s%s;',
              c.relname,format_type(s.seqtypid,NULL),s.seqincrement,s.seqmin,s.seqmax,s.seqstart,s.seqcache,
              CASE WHEN s.seqcycle THEN ' CYCLE' ELSE ' NO CYCLE' END)
FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace JOIN pg_sequence s ON s.seqrelid=c.oid
WHERE n.nspname='public' AND NOT EXISTS (
  SELECT 1 FROM pg_depend d WHERE d.objid=c.oid AND d.deptype='i'
) ORDER BY c.relname;
SELECT '';

-- Base tables. Defaults are added later after functions are available.
SELECT format(E'CREATE %sTABLE public.%I (\n%s\n);',
              CASE WHEN c.relpersistence='u' THEN 'UNLOGGED ' ELSE '' END,
              c.relname,
              string_agg(
                '  '||quote_ident(a.attname)||' '||format_type(a.atttypid,a.atttypmod)||
                CASE WHEN coll.oid IS NOT NULL AND coll.oid<>typ.typcollation THEN ' COLLATE '||quote_ident(coll_ns.nspname)||'.'||quote_ident(coll.collname) ELSE '' END||
                CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY' WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END||
                CASE WHEN a.attgenerated<>'' THEN ' GENERATED ALWAYS AS ('||pg_get_expr(ad.adbin,ad.adrelid)||') STORED' ELSE '' END||
                CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END,
                E',\n' ORDER BY a.attnum),
              CASE WHEN c.relkind='p' THEN ' PARTITION BY '||pg_get_partkeydef(c.oid) ELSE '' END)
FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
JOIN pg_attribute a ON a.attrelid=c.oid AND a.attnum>0 AND NOT a.attisdropped
JOIN pg_type typ ON typ.oid=a.atttypid
LEFT JOIN pg_attrdef ad ON ad.adrelid=a.attrelid AND ad.adnum=a.attnum
LEFT JOIN pg_collation coll ON coll.oid=a.attcollation
LEFT JOIN pg_namespace coll_ns ON coll_ns.oid=coll.collnamespace
WHERE n.nspname='public' AND c.relkind IN ('r','p')
GROUP BY c.oid,c.relname,c.relpersistence,c.relkind ORDER BY c.relname;
SELECT '';

-- Public functions and procedures. Extension-owned routines are excluded.
