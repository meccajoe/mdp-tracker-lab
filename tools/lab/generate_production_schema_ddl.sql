SELECT format('REVOKE ALL ON FUNCTION %s FROM PUBLIC;',p.oid::regprocedure::text)
FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
WHERE n.nspname='public' AND p.prokind IN ('f','p')
  AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid=p.oid AND d.deptype='e')
ORDER BY p.oid::regprocedure::text;

WITH grants AS (
 SELECT c.oid,c.relkind,c.relname,coalesce(r.rolname,'PUBLIC') grantee,a.privilege_type,a.is_grantable
 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
 CROSS JOIN LATERAL aclexplode(c.relacl) a LEFT JOIN pg_roles r ON r.oid=a.grantee
 WHERE n.nspname='public' AND c.relacl IS NOT NULL
)
SELECT format('GRANT %s ON %s public.%I TO %s%s;',
              string_agg(privilege_type,', ' ORDER BY privilege_type),
              CASE WHEN relkind='S' THEN 'SEQUENCE' ELSE 'TABLE' END,relname,
              CASE WHEN grantee='PUBLIC' THEN 'PUBLIC' ELSE quote_ident(grantee) END,
              CASE WHEN is_grantable THEN ' WITH GRANT OPTION' ELSE '' END)
FROM grants GROUP BY oid,relkind,relname,grantee,is_grantable ORDER BY relname,grantee,is_grantable;

WITH grants AS (
 SELECT p.oid,p.oid::regprocedure::text identity,coalesce(r.rolname,'PUBLIC') grantee,a.privilege_type,a.is_grantable
 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
 CROSS JOIN LATERAL aclexplode(coalesce(p.proacl,acldefault('f',p.proowner))) a LEFT JOIN pg_roles r ON r.oid=a.grantee
 WHERE n.nspname='public' AND p.prokind IN ('f','p')
   AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid=p.oid AND d.deptype='e')
)
SELECT format('GRANT %s ON FUNCTION %s TO %s%s;',
              string_agg(privilege_type,', ' ORDER BY privilege_type),identity,
              CASE WHEN grantee='PUBLIC' THEN 'PUBLIC' ELSE quote_ident(grantee) END,
              CASE WHEN is_grantable THEN ' WITH GRANT OPTION' ELSE '' END)
FROM grants GROUP BY oid,identity,grantee,is_grantable ORDER BY identity,grantee,is_grantable;
