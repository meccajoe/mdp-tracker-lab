-- Public enum and domain types.
SELECT format('CREATE TYPE public.%I AS ENUM (%s);',t.typname,
              string_agg(quote_literal(e.enumlabel),', ' ORDER BY e.enumsortorder))
FROM pg_type t JOIN pg_namespace n ON n.oid=t.typnamespace
JOIN pg_enum e ON e.enumtypid=t.oid
WHERE n.nspname='public' GROUP BY t.oid,t.typname ORDER BY t.typname;
SELECT format('CREATE DOMAIN public.%I AS %s%s%s;',t.typname,
              format_type(t.typbasetype,t.typtypmod),
              CASE WHEN t.typnotnull THEN ' NOT NULL' ELSE '' END,
              CASE WHEN t.typdefault IS NOT NULL THEN ' DEFAULT '||t.typdefault ELSE '' END)
FROM pg_type t JOIN pg_namespace n ON n.oid=t.typnamespace
WHERE n.nspname='public' AND t.typtype='d' ORDER BY t.typname;
