-- Deferred column defaults.
SELECT format('ALTER TABLE ONLY public.%I ALTER COLUMN %I SET DEFAULT %s;',
              c.relname,a.attname,pg_get_expr(ad.adbin,ad.adrelid))
FROM pg_attrdef ad JOIN pg_attribute a ON a.attrelid=ad.adrelid AND a.attnum=ad.adnum
JOIN pg_class c ON c.oid=ad.adrelid JOIN pg_namespace n ON n.oid=c.relnamespace
WHERE n.nspname='public' AND c.relkind IN ('r','p') AND a.attidentity='' AND a.attgenerated=''
ORDER BY c.relname,a.attnum;

-- Serial sequence ownership.
SELECT format('ALTER SEQUENCE public.%I OWNED BY public.%I.%I;',seq.relname,tbl.relname,a.attname)
FROM pg_depend d JOIN pg_class seq ON seq.oid=d.objid AND seq.relkind='S'
JOIN pg_class tbl ON tbl.oid=d.refobjid JOIN pg_namespace n ON n.oid=tbl.relnamespace
JOIN pg_attribute a ON a.attrelid=tbl.oid AND a.attnum=d.refobjsubid
WHERE n.nspname='public' AND d.deptype='a' ORDER BY seq.relname;
SELECT '';

-- Constraints, including foreign keys to managed auth/storage schemas.
SELECT format('ALTER TABLE ONLY public.%I ADD CONSTRAINT %I %s;',c.relname,con.conname,pg_get_constraintdef(con.oid,true))
FROM pg_constraint con JOIN pg_class c ON c.oid=con.conrelid JOIN pg_namespace n ON n.oid=c.relnamespace
WHERE n.nspname='public' AND con.contype IN ('p','u','c','x','f')
ORDER BY CASE con.contype WHEN 'p' THEN 1 WHEN 'u' THEN 2 WHEN 'c' THEN 3 WHEN 'x' THEN 4 WHEN 'f' THEN 5 ELSE 6 END,c.relname,con.conname;
SELECT '';

-- Non-constraint indexes.
SELECT pg_get_indexdef(i.indexrelid)||';'
FROM pg_index i JOIN pg_class c ON c.oid=i.indrelid JOIN pg_namespace n ON n.oid=c.relnamespace
WHERE n.nspname='public' AND NOT EXISTS (SELECT 1 FROM pg_constraint con WHERE con.conindid=i.indexrelid)
ORDER BY c.relname,i.indexrelid::regclass::text;
SELECT '';

-- Views contain definitions only; no materialized-view rows are copied.
SELECT format(E'CREATE VIEW public.%I%s AS\n%s;',c.relname,
              CASE WHEN c.reloptions IS NOT NULL THEN ' WITH ('||array_to_string(c.reloptions,', ')||')' ELSE '' END,
              rtrim(pg_get_viewdef(c.oid,true),';'))
FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
WHERE n.nspname='public' AND c.relkind='v'
ORDER BY (
  SELECT count(*) FROM pg_rewrite rw JOIN pg_depend d ON d.classid='pg_rewrite'::regclass AND d.objid=rw.oid
  JOIN pg_class dependency ON dependency.oid=d.refobjid JOIN pg_namespace dependency_ns ON dependency_ns.oid=dependency.relnamespace
  WHERE rw.ev_class=c.oid AND dependency_ns.nspname='public' AND dependency.relkind IN ('v','m') AND dependency.oid<>c.oid
),c.relname;
SELECT format(E'CREATE MATERIALIZED VIEW public.%I%s AS\n%s\nWITH NO DATA;',c.relname,
              CASE WHEN c.reloptions IS NOT NULL THEN ' WITH ('||array_to_string(c.reloptions,', ')||')' ELSE '' END,
              rtrim(pg_get_viewdef(c.oid,true),';'))
FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
WHERE n.nspname='public' AND c.relkind='m' ORDER BY c.relname;
SELECT '';

-- Row-level security and policies.
SELECT format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;',c.relname)
FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
WHERE n.nspname='public' AND c.relkind IN ('r','p') AND c.relrowsecurity ORDER BY c.relname;
SELECT format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY;',c.relname)
FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
WHERE n.nspname='public' AND c.relkind IN ('r','p') AND c.relforcerowsecurity ORDER BY c.relname;
SELECT format('CREATE POLICY %I ON public.%I AS %s FOR %s TO %s%s%s;',p.polname,c.relname,
              CASE WHEN p.polpermissive THEN 'PERMISSIVE' ELSE 'RESTRICTIVE' END,
              CASE p.polcmd WHEN 'r' THEN 'SELECT' WHEN 'a' THEN 'INSERT' WHEN 'w' THEN 'UPDATE' WHEN 'd' THEN 'DELETE' ELSE 'ALL' END,
              (SELECT string_agg(CASE WHEN role_oid=0 THEN 'PUBLIC' ELSE quote_ident(r.rolname) END,', ' ORDER BY role_oid)
               FROM unnest(p.polroles) role_oid LEFT JOIN pg_roles r ON r.oid=role_oid),
              CASE WHEN p.polqual IS NOT NULL THEN ' USING ('||pg_get_expr(p.polqual,p.polrelid)||')' ELSE '' END,
              CASE WHEN p.polwithcheck IS NOT NULL THEN ' WITH CHECK ('||pg_get_expr(p.polwithcheck,p.polrelid)||')' ELSE '' END)
FROM pg_policy p JOIN pg_class c ON c.oid=p.polrelid JOIN pg_namespace n ON n.oid=c.relnamespace
WHERE n.nspname='public' ORDER BY c.relname,p.polname;
SELECT '';

